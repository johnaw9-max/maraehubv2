#!/usr/bin/env node
'use strict';

// Baseline generator: writes the STRUCTURE (no data) of the reference project
// (Opeke) as one idempotent SQL file, so a new marae can be built in one step
// instead of replaying 170+ migrations.
//
//   node scripts/generate-baseline-migration.js            write supabase/baseline/
//   node scripts/generate-baseline-migration.js --check    exit 1 if the file is stale
//   node scripts/generate-baseline-migration.js --ref=<ref> use another reference project
//
// Read-only: only catalog queries (pg_catalog / information_schema / storage
// bucket config). It never reads a row of business data and never writes to a
// database. Uses the already-logged-in `supabase` CLI; never asks for a key.
//
// The generated file refuses to run on a project whose public schema already
// has tables, so it can never touch a live marae.

const { spawnSync } = require('child_process');
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const REPO = path.join(__dirname, '..');
const OUT_DIR = path.join(REPO, 'supabase', 'baseline');
const OUT_SQL = path.join(OUT_DIR, 'baseline.sql');
const OUT_META = path.join(OUT_DIR, 'baseline.meta.json');
const OUT_VERIFY = path.join(OUT_DIR, 'verify-baseline.sql');
const REGISTRY = path.join(__dirname, 'marae-registry.json');

const args = process.argv.slice(2);
const CHECK = args.includes('--check');
const refArg = (args.find((a) => a.startsWith('--ref=')) || '').slice(6);

function die(msg) { console.error(`\nSTOP: ${msg}`); process.exit(1); }

function referenceRef() {
  if (refArg) return refArg;
  const reg = JSON.parse(fs.readFileSync(REGISTRY, 'utf8'));
  const projects = reg.projects || reg;
  const list = Array.isArray(projects) ? projects : Object.values(projects);
  const prod = list.find((p) => /opeke/i.test(p.name || '') || p.reference === true);
  if (!prod || !(prod.ref || prod.project_ref)) die('could not find the reference project in scripts/marae-registry.json; pass --ref=<ref>');
  return prod.ref || prod.project_ref;
}

function query(sql, ref) {
  console.log(`$ supabase db query --linked (read-only catalog query)  (project: ${ref})`);
  const res = spawnSync('npx', ['supabase', 'db', 'query', '--linked', '--output', 'json', sql], { encoding: 'utf8', maxBuffer: 1024 * 1024 * 200 });
  if (res.error || res.status !== 0) die(`query failed: ${(res.stderr || String(res.error)).trim().split('\n').slice(-3).join(' ')}`);
  let parsed;
  try { parsed = JSON.parse(res.stdout); } catch (e) { die(`could not parse CLI output: ${e.message}`); }
  const rows = Array.isArray(parsed) ? parsed : (parsed.rows || parsed.data || parsed.result || null);
  if (!Array.isArray(rows)) die(`unexpected CLI output shape (keys: ${Object.keys(parsed || {}).join(', ') || 'none'}); first 300 chars: ${res.stdout.slice(0, 300)}`);
  return rows;
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const ident = (s) => `"${String(s).replace(/"/g, '""')}"`;

function gather(ref) {
  const r = {};
  r.extensions = query(`select extname from pg_extension where extname in ('pgcrypto','uuid-ossp','pg_cron','pg_net','supabase_vault') order by 1`, ref);
  r.tables = query(`
    select c.relname as name, c.relrowsecurity as rls, c.relforcerowsecurity as force_rls,
      (select string_agg(format('%I %s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
         case when a.attidentity='a' then ' generated always as identity' when a.attidentity='d' then ' generated by default as identity' else '' end,
         case when a.attgenerated='s' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
              when d.adbin is not null then ' default ' || pg_get_expr(d.adbin, d.adrelid) else '' end
         || case when a.attnotnull then ' not null' else '' end), E',\\n  ' order by a.attnum)
       from pg_attribute a left join pg_attrdef d on d.adrelid=a.attrelid and d.adnum=a.attnum
       where a.attrelid=c.oid and a.attnum>0 and not a.attisdropped) as cols
    from pg_class c join pg_namespace n on n.oid=c.relnamespace
    where n.nspname='public' and c.relkind='r' order by c.relname`, ref);
  r.constraints = query(`
    select c.relname as tbl, con.conname as name, con.contype as type, pg_get_constraintdef(con.oid) as def
    from pg_constraint con join pg_class c on c.oid=con.conrelid join pg_namespace n on n.oid=c.relnamespace
    where n.nspname='public' and con.contype in ('p','u','c','f','x')
    order by case con.contype when 'p' then 1 when 'u' then 2 when 'c' then 3 when 'x' then 4 else 5 end, c.relname, con.conname`, ref);
  r.indexes = query(`
    select i.tablename as tbl, i.indexname as name, i.indexdef as def from pg_indexes i
    where i.schemaname='public'
      and not exists (select 1 from pg_constraint con join pg_class ic on ic.oid=con.conindid
                      where ic.relname=i.indexname and con.connamespace='public'::regnamespace)
    order by i.tablename, i.indexname`, ref);
  r.views = query(`select c.relname as name, pg_get_viewdef(c.oid, true) as def, c.reloptions as opts
    from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relkind='v' order by 1`, ref);
  r.functions = query(`select p.proname as name, pg_get_function_identity_arguments(p.oid) as args, pg_get_functiondef(p.oid) as def
    from pg_proc p join pg_namespace n on n.oid=p.pronamespace
    where n.nspname='public' and p.prokind='f'
      and not exists (select 1 from pg_depend d where d.objid=p.oid and d.deptype='e')
    order by 1, 2`, ref);
  r.triggers = query(`select n.nspname as sch, c.relname as tbl, t.tgname as name, pg_get_triggerdef(t.oid) as def
    from pg_trigger t join pg_class c on c.oid=t.tgrelid join pg_namespace n on n.oid=c.relnamespace
    where not t.tgisinternal and ((n.nspname='public') or (n.nspname='auth' and c.relname='users'))
    order by 1,2,3`, ref);
  r.policies = query(`select schemaname as sch, tablename as tbl, policyname as name, permissive, roles, cmd, qual, with_check
    from pg_policies where schemaname='public' or (schemaname='storage' and tablename='objects') order by 1,2,3`, ref);
  r.buckets = query(`select id, name, public, file_size_limit, allowed_mime_types from storage.buckets order by id`, ref);
  r.grants = query(`select table_name as tbl, grantee, string_agg(privilege_type, ', ' order by privilege_type) as privs
    from information_schema.role_table_grants where table_schema='public' and grantee in ('anon','authenticated','service_role')
    group by 1,2 order by 1,2`, ref);
  r.latest = query(`select max(version) as v, count(*) as n from supabase_migrations.schema_migrations`, ref)[0];
  return r;
}

function build(r, ref) {
  const L = [];
  const add = (s = '') => L.push(s);
  add('-- MaraeHub baseline: STRUCTURE ONLY, no data. GENERATED FILE: do not edit by hand.');
  add('-- Regenerate with: node scripts/generate-baseline-migration.js');
  add(`-- Represents the reference project's structure up to migration ${r.latest.v}.`);
  add('-- Migrations newer than that are applied afterwards by scripts/apply-to-all.sh.');
  add('');
  add('set check_function_bodies = off;');
  add('');
  add('do $guard$ begin');
  add("  if (select count(*) from information_schema.tables where table_schema='public' and table_type='BASE TABLE') > 0 then");
  add("    raise exception 'REFUSING TO RUN: this project already has tables in the public schema. The baseline is for brand-new empty projects only.';");
  add('  end if;');
  add('end $guard$;');
  add('');
  for (const e of r.extensions) add(`create extension if not exists ${ident(e.extname)};`);
  add('');
  add('-- TABLES');
  for (const t of r.tables) add(`create table if not exists public.${ident(t.name)} (\n  ${t.cols}\n);`);
  add('');
  add('-- CONSTRAINTS (primary keys and uniques first, foreign keys last)');
  for (const c of r.constraints) {
    add(`do $c$ begin alter table public.${ident(c.tbl)} add constraint ${ident(c.name)} ${c.def}; exception when duplicate_object or duplicate_table then null; end $c$;`);
  }
  add('');
  add('-- INDEXES');
  for (const i of r.indexes) add(i.def.replace(/^CREATE (UNIQUE )?INDEX /, 'CREATE $1INDEX IF NOT EXISTS ') + ';');
  add('');
  add('-- FUNCTIONS');
  for (const f of r.functions) add(f.def.replace(/^CREATE FUNCTION/, 'CREATE OR REPLACE FUNCTION') + ';\n');
  add('-- VIEWS');
  for (const v of r.views) add(`create or replace view public.${ident(v.name)}${v.opts ? ` with (${v.opts.join(',')})` : ''} as\n${v.def.replace(/;\s*$/, '')};`);
  add('');
  add('-- TRIGGERS');
  for (const t of r.triggers) {
    add(`drop trigger if exists ${ident(t.name)} on ${t.sch}.${ident(t.tbl)};`);
    add(`${t.def};`);
  }
  add('');
  add('-- ROW LEVEL SECURITY');
  for (const t of r.tables) {
    if (t.rls) add(`alter table public.${ident(t.name)} enable row level security;`);
    if (t.force_rls) add(`alter table public.${ident(t.name)} force row level security;`);
  }
  for (const p of r.policies) {
    const roles = (Array.isArray(p.roles) ? p.roles : String(p.roles).replace(/[{}]/g, '').split(',')).filter(Boolean);
    add(`drop policy if exists ${ident(p.name)} on ${p.sch}.${ident(p.tbl)};`);
    add(`create policy ${ident(p.name)} on ${p.sch}.${ident(p.tbl)} as ${p.permissive.toLowerCase()} for ${p.cmd.toLowerCase()} to ${roles.join(', ') || 'public'}` +
      `${p.qual ? ` using (${p.qual})` : ''}${p.with_check ? ` with check (${p.with_check})` : ''};`);
  }
  add('');
  add('-- STORAGE BUCKETS (configuration only)');
  for (const b of r.buckets) {
    add(`insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (${q(b.id)}, ${q(b.name)}, ${b.public}, ${b.file_size_limit == null ? 'null' : b.file_size_limit}, ${b.allowed_mime_types ? `array[${b.allowed_mime_types.map(q).join(',')}]::text[]` : 'null'}) on conflict (id) do nothing;`);
  }
  add('');
  add('-- TABLE GRANTS');
  for (const g of r.grants) add(`grant ${g.privs} on public.${ident(g.tbl)} to ${g.grantee};`);
  add('');
  return L.join('\n');
}

function verifySql(r) {
  return `-- Run on a freshly built project AFTER the baseline. Every row should say ok = true.
select 'tables' as what, ${r.tables.length} as expected, (select count(*) from information_schema.tables where table_schema='public' and table_type='BASE TABLE') as actual
union all select 'functions', ${r.functions.length}, (select count(*) from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public')
union all select 'indexes', ${r.indexes.length + r.constraints.filter((c) => ['p', 'u', 'x'].includes(c.type)).length}, (select count(*) from pg_indexes where schemaname='public')
union all select 'policies (public)', ${r.policies.filter((p) => p.sch === 'public').length}, (select count(*) from pg_policies where schemaname='public')
union all select 'policies (storage)', ${r.policies.filter((p) => p.sch === 'storage').length}, (select count(*) from pg_policies where schemaname='storage')
union all select 'buckets', ${r.buckets.length}, (select count(*) from storage.buckets);
`;
}

const ref = referenceRef();
console.log(`Reference project: ${ref}`);
const link = spawnSync('npx', ['supabase', 'link', '--project-ref', ref], { encoding: 'utf8' });
if (link.status !== 0) die('could not link the reference project with the supabase CLI (run `npx supabase login` once)');

const data = gather(ref);
if (!data.tables.length || !data.latest) die('the reference project returned no tables or no migration history; refusing to write an empty baseline');
const sql = build(data, ref);
const hash = crypto.createHash('sha256').update(sql).digest('hex');
const meta = { reference_ref: ref, represents_through_migration: data.latest.v, tracked_migrations: Number(data.latest.n), sha256: hash,
  counts: { tables: data.tables.length, functions: data.functions.length, policies: data.policies.length, buckets: data.buckets.length } };

if (CHECK) {
  if (!fs.existsSync(OUT_SQL)) die('no baseline exists yet; run without --check');
  const have = crypto.createHash('sha256').update(fs.readFileSync(OUT_SQL, 'utf8')).digest('hex');
  if (have !== hash) die(`baseline is STALE: the reference project's structure has changed since it was generated. Regenerate and review the diff.`);
  console.log('Baseline is up to date.');
  process.exit(0);
}
fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(OUT_SQL, sql);
fs.writeFileSync(OUT_META, JSON.stringify(meta, null, 2) + '\n');
fs.writeFileSync(OUT_VERIFY, verifySql(data));
console.log(`Wrote ${path.relative(REPO, OUT_SQL)} (${data.tables.length} tables, ${data.functions.length} functions, ${data.policies.length} policies). Review the diff before committing.`);
