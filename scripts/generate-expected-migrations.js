#!/usr/bin/env node
// Regenerates supabase/functions/check-deadlines/expectedMigrations.ts from
// the local supabase/migrations/ directory -- version strings only.
//
// Same shape and same discipline as generate-expected-schema.js: plain
// Node (not Deno/.ts), run manually, commit the output, nothing enforces
// this gets re-run automatically when a migration is added.
//
// Exists for the migration_tracking_drift check (maintenance shield):
// check-deadlines has no filesystem/git access to the repo at runtime, so
// it can't read supabase/migrations/ directly -- same reason schema_drift
// needs expectedSchema.ts instead of reading schema.sql live.

const fs = require('fs');
const path = require('path');

const MIGRATIONS_DIR = path.join(__dirname, '..', 'supabase', 'migrations');
const OUTPUT_PATH = path.join(__dirname, '..', 'supabase', 'functions', 'check-deadlines', 'expectedMigrations.ts');

// Matches the Supabase CLI's own migration filename convention: a 14-digit
// timestamp, then an underscore, then a descriptive name -- OR the 7 real,
// early bare-8-digit-date files this repo also has (20260608_..., etc.,
// predating the 14-digit convention; confirmed real, tracked, applied
// migrations, not a typo). Files that don't match either shape (e.g.
// interest_register.sql -- not a dated migration, a one-off reference file
// living in this directory) are silently skipped, not treated as an error.
const VERSION_RE = /^(\d{14}|\d{8})_/;

const files = fs.readdirSync(MIGRATIONS_DIR);
const versions = [];
for (const file of files) {
  const match = file.match(VERSION_RE);
  if (match) versions.push(match[1]);
}
versions.sort();

if (versions.length === 0) {
  console.error('No versioned migration files found -- refusing to write an empty/broken output file.');
  process.exit(1);
}

const header = `// AUTO-GENERATED by scripts/generate-expected-migrations.js from
// supabase/migrations/. Do not edit by hand -- re-run the generator
// instead. Version strings only (the 14-digit timestamp prefix), not
// filenames or content. Regenerate whenever a migration file is added and
// commit the result; nothing enforces this automatically.

`;

const body = `export const EXPECTED_MIGRATIONS: string[] = ${JSON.stringify(versions, null, 2)};\n`;

fs.writeFileSync(OUTPUT_PATH, header + body);

console.log(`Wrote ${OUTPUT_PATH}`);
console.log(`${versions.length} migration versions`);
