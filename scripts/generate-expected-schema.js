#!/usr/bin/env node
// Regenerates supabase/functions/check-deadlines/expectedSchema.ts from
// schema.sql -- table/column names only (ClickUp 86d3u7790, Stage 2d).
//
// Plain Node, not the generate-expected-schema.ts originally named in the
// design: neither Deno nor the `typescript` package is available on this
// machine (confirmed separately, ClickUp 86d3wrm1v), so a literal .ts
// script couldn't actually run here. The generator's own logic needs no
// type-checking or Deno APIs -- only its output (expectedSchema.ts) needs
// to be valid TypeScript, since that's what the Deno edge function
// actually imports.
//
// Run manually and commit the output whenever schema.sql changes -- same
// manual-but-deliberate discipline as every migration and deploy this
// project already uses. Nothing enforces this gets re-run automatically;
// that's a named, not-solved limitation, logged on the ClickUp task.

const fs = require('fs');
const path = require('path');

const SCHEMA_PATH = path.join(__dirname, '..', 'schema.sql');
const OUTPUT_PATH = path.join(__dirname, '..', 'supabase', 'functions', 'check-deadlines', 'expectedSchema.ts');

const schema = fs.readFileSync(SCHEMA_PATH, 'utf8');

// Matches this repo's schema.sql convention exactly (confirmed against the
// 10 August re-sync): "create table if not exists <name> (\n<cols>\n);",
// one column per line, each indented exactly two spaces.
const TABLE_RE = /create table if not exists (\w+) \(\n([\s\S]*?)\n\);/g;

const expected = {};
let match;
while ((match = TABLE_RE.exec(schema)) !== null) {
  const [, tableName, body] = match;
  const columns = [];
  for (const line of body.split('\n')) {
    const colMatch = line.match(/^ {2}(\w+)\s/);
    if (colMatch) columns.push(colMatch[1]);
  }
  expected[tableName] = columns;
}

const tableCount = Object.keys(expected).length;
const columnCount = Object.values(expected).reduce((sum, cols) => sum + cols.length, 0);

if (tableCount === 0) {
  console.error('No tables extracted from schema.sql -- refusing to write an empty/broken output file.');
  process.exit(1);
}

const header = `// AUTO-GENERATED by scripts/generate-expected-schema.js from schema.sql.
// Do not edit by hand -- re-run the generator instead. Table/column names
// only (ClickUp 86d3u7790, Stage 2d) -- not types, constraints, or defaults.
// Regenerate whenever schema.sql changes and commit the result; nothing
// enforces this automatically (named limitation, see ClickUp task).

`;

const body = `export const EXPECTED_SCHEMA: Record<string, string[]> = ${JSON.stringify(expected, null, 2)};\n`;

fs.writeFileSync(OUTPUT_PATH, header + body);

console.log(`Wrote ${OUTPUT_PATH}`);
console.log(`${tableCount} tables, ${columnCount} columns`);
