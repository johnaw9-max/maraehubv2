#!/usr/bin/env node
// Regenerates supabase/functions/check-deadlines/expectedDeployment.ts from
// scripts/marae-registry.json and the supabase/functions directory listing
// (14yhc7kw74b, apply-to-all refinement).
//
// Plain Node, same reason as generate-expected-schema.js: neither Deno nor
// the `typescript` package is available on this machine, but the output
// file only needs to be valid TypeScript, not run through either.
//
// The master function list is read from the filesystem, not hand-maintained
// -- that's the actual source of truth for "what functions exist in this
// codebase", same principle as EXPECTED_SCHEMA reading schema.sql instead of
// a separately-maintained table list. check-deadlines itself is excluded
// from the master list unconditionally: probing its own reachability from
// within its own currently-running invocation is trivially always true.
//
// For each project in the registry, expected_functions is the master list
// minus that project's excluded_functions -- the generator does this
// subtraction once here so check-deadlines doesn't have to re-derive it at
// runtime, it just logs excluded_functions/excluded_jobs as exempt when
// something in that list is confirmed missing.
//
// Run manually and commit the output whenever marae-registry.json or the
// functions directory changes -- same manual-but-deliberate discipline as
// generate-expected-schema.js. Nothing enforces this gets re-run
// automatically; that's a named, not-solved limitation, same as that
// generator's.

const fs = require('fs');
const path = require('path');

const REGISTRY_PATH = path.join(__dirname, 'marae-registry.json');
const FUNCTIONS_DIR = path.join(__dirname, '..', 'supabase', 'functions');
const OUTPUT_PATH = path.join(__dirname, '..', 'supabase', 'functions', 'check-deadlines', 'expectedDeployment.ts');

const registry = JSON.parse(fs.readFileSync(REGISTRY_PATH, 'utf8'));

const masterFunctions = fs.readdirSync(FUNCTIONS_DIR, { withFileTypes: true })
  .filter(e => e.isDirectory())
  .map(e => e.name)
  .filter(name => name !== 'check-deadlines')
  .sort();

if (masterFunctions.length === 0) {
  console.error('No function directories found under supabase/functions -- refusing to write an empty/broken output file.');
  process.exit(1);
}

const expected = {};
for (const project of registry.projects) {
  const excludedFunctions = project.excluded_functions || [];
  const excludedJobs = project.excluded_jobs || [];
  const excludedNames = new Set(excludedFunctions.map(e => e.name));
  for (const ex of excludedFunctions) {
    if (!masterFunctions.includes(ex.name)) {
      console.error(`${project.name}: excluded_functions references "${ex.name}", which has no directory under supabase/functions.`);
      process.exit(1);
    }
    if (!ex.reason) {
      console.error(`${project.name}: excluded_functions entry "${ex.name}" has no reason -- every exclusion needs one.`);
      process.exit(1);
    }
  }
  for (const ex of excludedJobs) {
    if (!ex.reason) {
      console.error(`${project.name}: excluded_jobs entry "${ex.name}" has no reason -- every exclusion needs one.`);
      process.exit(1);
    }
  }
  expected[project.ref] = {
    name: project.name,
    expected_functions: masterFunctions.filter(name => !excludedNames.has(name)),
    excluded_functions: excludedFunctions,
    excluded_jobs: excludedJobs,
  };
}

const projectCount = Object.keys(expected).length;

const header = `// AUTO-GENERATED by scripts/generate-expected-deployment.js from
// scripts/marae-registry.json and the supabase/functions directory listing.
// Do not edit by hand -- re-run the generator instead. Keyed by project ref
// (matched at runtime against this project's own SUPABASE_URL). For each
// project: expected_functions is every function in the repo minus that
// project's own excluded_functions; excluded_functions/excluded_jobs are
// kept alongside so a confirmed-missing excluded item can be logged as
// exempt, with its reason, instead of alerting. Regenerate whenever
// marae-registry.json or the functions directory changes and commit the
// result; nothing enforces this automatically (named limitation, same as
// expectedSchema.ts's own generator).

`;

const body = `export const MASTER_FUNCTIONS: string[] = ${JSON.stringify(masterFunctions, null, 2)};

export const EXPECTED_DEPLOYMENT: Record<string, {
  name: string;
  expected_functions: string[];
  excluded_functions: { name: string; reason: string }[];
  excluded_jobs: { name: string; reason: string }[];
}> = ${JSON.stringify(expected, null, 2)};\n`;

fs.writeFileSync(OUTPUT_PATH, header + body);

console.log(`Wrote ${OUTPUT_PATH}`);
console.log(`${masterFunctions.length} functions in the master list, ${projectCount} projects`);
